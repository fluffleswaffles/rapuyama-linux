function createDeviceCard(device) {
  const column = document.createElement('div');
  column.className = 'col-6 col-md-4 col-lg-3';

  const card = document.createElement('article');
  card.className = 'card h-100';

  const imageFrame = document.createElement('div');
  imageFrame.className = 'bg-light d-flex align-items-center justify-content-center p-3';
  imageFrame.style.height = '240px';

  const image = document.createElement('img');
  image.className = 'img-fluid';
  image.src = device.image;
  image.alt = device.image === placeholderImage
    ? `Illustration placeholder for ${device.name}`
    : device.name;
  image.loading = 'lazy';
  image.style.maxHeight = '100%';
  image.style.objectFit = 'contain';
  imageFrame.append(image);

  const body = document.createElement('div');
  body.className = 'card-body';

  const title = document.createElement('h3');
  title.className = 'card-title h6 mb-2';
  title.textContent = device.name;
  body.append(title);

  const credit = imageCredits[device.image];
  const caption = document.createElement('p');
  caption.className = 'small text-muted mb-0';
  if (credit) {
    const source = document.createElement('a');
    source.href = credit.source;
    source.target = '_blank';
    source.rel = 'noopener noreferrer';
    source.textContent = `Photo by ${credit.artist}`;

    const license = document.createElement('a');
    license.href = credit.licenseUrl;
    license.target = '_blank';
    license.rel = 'noopener noreferrer';
    license.textContent = credit.license;

    caption.append(source, document.createTextNode(', '), license);
  } else {
    caption.textContent = 'Illustration placeholder';
  }
  body.append(caption);

  card.append(imageFrame, body);
  column.append(card);
  return column;
}

for (const group of deviceGroups) {
  const target = document.getElementById(group.target);
  for (const device of group.devices) {
    target.append(createDeviceCard(device));
  }
}
