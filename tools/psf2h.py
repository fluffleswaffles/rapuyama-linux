#!/usr/bin/env python3
"""PSF1/PSF2 console fonts (8 px wide) -> C arrays of printable ASCII glyphs.

usage: psf2h.py <out.h> <name>=<font.psf[.gz]> [...]
e.g.   psf2h.py font.h font16=/usr/share/consolefonts/Lat15-Terminus16.psf.gz
writes `static const unsigned char <name>[95][<height>]` for ' '..'~',
one byte per row, msb = leftmost pixel. Glyphs are looked up through the
font's unicode table when it has one.
"""
import gzip
import struct
import sys


def load(path):
    data = (gzip.open if path.endswith('.gz') else open)(path, 'rb').read()
    if data[:2] == b'\x36\x04':                      # psf1
        mode, h = data[2], data[3]
        n, w, off, uni = (512 if mode & 1 else 256), 8, 4, mode & 2
        glyphs = [data[off + i * h: off + (i + 1) * h] for i in range(n)]
        table, pos = {}, off + n * h
        if uni:
            for g in range(n):
                while True:
                    (u,) = struct.unpack_from('<H', data, pos)
                    pos += 2
                    if u == 0xffff:
                        break
                    if u != 0xfffe:
                        table.setdefault(u, g)
        return w, h, glyphs, table
    magic, ver, hsz, flags, n, size, h, w = struct.unpack_from('<8I', data)
    assert magic == 0x864ab572, path
    glyphs = [data[hsz + i * size: hsz + (i + 1) * size] for i in range(n)]
    table, pos = {}, hsz + n * size
    if flags & 1:
        for g in range(n):
            end = data.index(b'\xff', pos)
            for seq in data[pos:end].split(b'\xfe')[:1]:
                for ch in seq.decode('utf-8', 'replace'):
                    table.setdefault(ord(ch), g)
            pos = end + 1
    return w, h, glyphs, table


def main(out, specs):
    lines = ['/* generated by tools/psf2h.py, do not edit */']
    for spec in specs:
        name, path = spec.split('=', 1)
        w, h, glyphs, table = load(path)
        assert w == 8, '%s: %d px wide, only 8 supported' % (path, w)
        lines.append('/* %s: %s */' % (name, path.rsplit('/', 1)[-1]))
        lines.append('static const unsigned char %s[95][%d] = {' % (name, h))
        for c in range(32, 127):
            g = glyphs[table.get(c, c)]
            lines.append('\t{ %s },\t/* %r */' % (', '.join('0x%02x' % b for b in g[:h]), chr(c)))
        lines.append('};')
    with open(out, 'w') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2:])
