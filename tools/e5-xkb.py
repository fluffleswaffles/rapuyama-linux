#!/usr/bin/env python3
"""Nokia E5 X keymap -> linux/initramfs/e5.xkb (installed as /etc/e5.xkb).

The same layers as the console (e5-kmap.py, table in e5_keys.py), as XKB
levels: 1 base, 2 Shift, 3 Sym (ISO_Level3_Latch: held or one-shot), 5 Fn
(one-shot latch, no lock). X-only front keys (design 2.3, option A): the
right soft key is a one-shot Ctrl, Mail toggles pointer mode (MouseKeys);
the arrows move the pointer and Enter clicks while it is on.
@STEP@ = pointer step in pixels, filled in by e5-browser.sh.
usage: e5-xkb.py <out.xkb>
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from e5_keys import (KC, COMMA, DOT, BKSP, AT, QUEST, UP, DOWN, LEFT,  # noqa: E402
                     RIGHT, SYM, SYM_KC, BASE_KC, FN_LAYER, xkb_name)

ROWS = {'AD': 'QWERTYUIOP', 'AC': 'ASDFGHJKL', 'AB': 'ZXCVBNM'}
XKEY = {KC[c]: '%s%02d' % (r, i + 1) for r, cs in ROWS.items() for i, c in enumerate(cs)}
XKEY.update({COMMA: 'AB08', DOT: 'AB09', QUEST: 'AB10', AT: 'TLDE', BKSP: 'BKSP',
             UP: 'UP', DOWN: 'DOWN', LEFT: 'LEFT', RIGHT: 'RGHT'})
NAV = {UP: ('Up', '+0', '-@STEP@'), DOWN: ('Down', '+0', '+@STEP@'),
       LEFT: ('Left', '-@STEP@', '+0'), RIGHT: ('Right', '+@STEP@', '+0')}


def levels(kc):
    """8 XKB levels: base, Shift, Sym, Shift+Sym, Fn, Shift+Fn, -, -
    (a layer without an entry types the base key, as the console does)"""
    name = next((c for c, k in KC.items() if k == kc), None)
    if name:
        base, shift = name.lower(), name
    elif kc in BASE_KC:
        base = shift = xkb_name(BASE_KC[kc])
    elif kc == BKSP:
        base = shift = 'BackSpace'
    else:
        base = shift = NAV[kc][0]
    sym = SYM.get(name) if name else SYM_KC.get(kc)
    sym = xkb_name(sym) if sym else base
    fn = xkb_name(FN_LAYER[kc]) if kc in FN_LAYER else base
    return [base, shift, sym, sym, fn, fn, 'NoSymbol', 'NoSymbol']


def key(kc):
    syms = ', '.join(levels(kc))
    out = '\t\tkey <%s> { type[Group1] = "EIGHT_LEVEL", symbols[Group1] = [ %s ]' % (XKEY[kc], syms)
    if kc in NAV:
        _, x, y = NAV[kc]
        acts = ['MovePtr(x=%s,y=%s)' % (x, y)] * 4 + ['NoAction()'] * 4
        out += ', actions[Group1] = [ %s ]' % ', '.join(acts)
    return out + ' };\n'


def build():
    keys = ''.join(key(kc) for kc in sorted(XKEY, key=lambda k: XKEY[k]))
    return '''// generated by tools/e5-xkb.py, do not edit
xkb_keymap {
	xkb_keycodes { include "evdev+aliases(qwerty)" };
	xkb_types { include "complete" };
	xkb_compat { include "complete" };
	xkb_symbols {
		include "pc+us+inet(evdev)"
		// level 5 (Fn) on Mod3, spelled out: older xkeyboard-config (the
		// phone's) lacks the level5 modifier_mapping section
		key <LVL5> { [ ISO_Level5_Shift ] };
		modifier_map Mod3 { <LVL5> };
		// fn (bottom left): the Fn layer for one key
		key <RCTL> { type[Group1] = "ONE_LEVEL", symbols[Group1] = [ ISO_Level5_Latch ],
			actions[Group1] = [ LatchMods(modifiers=LevelFive,clearLocks) ] };
		// sym: the printed symbols, held or one-shot
		key <RALT> { type[Group1] = "ONE_LEVEL", symbols[Group1] = [ ISO_Level3_Latch ] };
		// right soft key: Ctrl for one key
		key <LWIN> { type[Group1] = "ONE_LEVEL", symbols[Group1] = [ Control_L ],
			actions[Group1] = [ LatchMods(modifiers=Control,clearLocks) ] };
		// mail: pointer mode on/off
		key <CAPS> { type[Group1] = "ONE_LEVEL", symbols[Group1] = [ Pointer_EnableKeys ] };
		// enter (navi centre): click while pointer mode is on
		key <RTRN> { symbols[Group1] = [ Return ], actions[Group1] = [ PtrBtn(button=1) ] };
%s	};
	xkb_geometry { include "pc(pc105)" };
};
''' % keys


if __name__ == '__main__':
    with open(sys.argv[1], 'w') as f:
        f.write(build())
