#!/usr/bin/env python3
"""Nokia E5 Fn layer (tools/e5_keys.py) -> linux/initramfs/e5-keyd/layer.h,
the table e5-keyd draws its key picture from.
usage: e5-keyd-layer.py <out.h>
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from e5_keys import FN_LAYER, PICTURE_ROWS, KEY_LABEL  # noqa: E402

NAVLINE = 'fn+navi  ^ PgUp  v PgDn  < Home  > End'


def c_str(s):
    return '"%s"' % s.replace('\\', '\\\\').replace('"', '\\"')


def build():
    rows = []
    for row in PICTURE_ROWS:
        cells = []
        for kc in row:
            sym = FN_LAYER.get(kc, '')
            accent = sym.startswith('F') and sym[1:].isdigit() or sym == 'Del'
            cells.append('\t\t{ %s, %s, %s },' % (c_str(sym), c_str(KEY_LABEL[kc]),
                                                  'true' if accent else 'false'))
        rows.append('\t{\n%s\n\t},' % '\n'.join(cells))
    return ('/* generated by tools/e5-keyd-layer.py from tools/e5_keys.py, do not edit */\n'
            'const struct keyd_cell keyd_cells[3][10] = {\n%s\n};\n'
            'const char keyd_navline[] = %s;\n') % ('\n'.join(rows), c_str(NAVLINE))


if __name__ == '__main__':
    with open(sys.argv[1], 'w') as f:
        f.write(build())
